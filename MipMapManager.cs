        public static bool ShouldSkipMipmaps(string filePath)
        {
            string fileName = Path.GetFileNameWithoutExtension(filePath);
            string baseName = StripNumericSuffix(fileName);

            return _noMipMapTextures.Contains(baseName) ||
                   _noMipMapTextures.Contains(baseName + ".bmp");
        }

        private static string StripNumericSuffix(string fileName)
        {
            int idx = fileName.LastIndexOf('_');
            if (idx < 0) return fileName;

            string suffix = fileName.Substring(idx + 1);
            return suffix.All(char.IsDigit)
                ? fileName.Substring(0, idx)
                : fileName;
        }
